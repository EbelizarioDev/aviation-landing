const BY_ID = new Map(AIRCRAFT.map((a) => [a.id, a]));

export function getAircraft(id) {
  const a = BY_ID.get(id);
  if (!a) throw new Error(`unknown aircraft: ${id}`);
  return a;
}

export function landingFlapIndex(a) {
  return a.flaps.length - 1;
}

export function isRetractable(a) {
  return a.gear === 'retractable';
}
